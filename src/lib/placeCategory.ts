/**
 * 앞에서부터 먼저 걸리는 것이 이긴다.
 * - 이마트24(편의점)가 이마트(대형마트)보다 앞이어야 한다.
 * - MT1·OL7이 BK9보다 앞이어야 한다 — 농협·신협·수협·새마을금고는 전부 자기 이름을 건
 *   하나로마트·주유소를 운영한다(실측: 농협하나로마트→MT1, 농협/신협/수협/새마을금고
 *   +주유소→OL7). BK9 쪽 패턴을 낱개로 좁히는 대신, 더 구체적인 카테고리를 앞에 둬서
 *   한 번에 막는다.
 */
const TABLE: [RegExp, string][] = [
  [/편의점|씨유|\bcu\b|gs25|세븐일레븐|이마트24|미니스톱|이마트24시/i, 'CS2'],
  [/대형마트|이마트|홈플러스|롯데마트|코스트코|하나로마트/i, 'MT1'],
  // 충전소는 제외 — 실측: "전기차충전소"는 category_group_code가 빈 값이라 필터링하면 0건.
  [/주유소|gs칼텍스|sk에너지|현대오일뱅크|에쓰오일|s-oil/i, 'OL7'],
  // 은행(?!나무) — "은행나무"(가로수·관광명소, 실측 AT4/빈 값)까지 은행으로 묶지 않는다.
  // \batm\b — 그냥 atm이면 "atmosphere"(카페, 실측 CE7) 같은 영단어 안의 부분 문자열까지 집는다.
  [/은행(?!나무)|\batm\b|새마을금고|신협|농협|수협|우체국예금/i, 'BK9'],
  [/카페|커피|스타벅스|스벅|투썸|메가커피|컴포즈|빽다방|이디야|할리스|커피빈/i, 'CE7'],
  // 팜은 제외 — 실측: "팜"만으로는 성우팜(문구)·레코드팜(IT)·이블루팜(건강식품)이 걸리고
  // 약국인 건 "팜약국"뿐이다. pharmacy도 함께 제거(한국어 질의에 실릴 일이 없다).
  [/약국/i, 'PM9'],
  // 의원은 제외 — 실측: "국회의원회관"은 주차장·정치단체 사무실만 나오고 HP8은 없다.
  [/병원|치과|한의원|정형외과|내과|소아과|피부과|안과|이비인후과/i, 'HP8'],
  [/주차장|주차/i, 'PK6'],
  [/지하철역|전철역/i, 'SW8'],
  [/학교|초등학교|중학교|고등학교|대학교/i, 'SC4'],
  [/어린이집|유치원/i, 'PS3'],
  [/숙박|호텔|모텔|펜션|게스트하우스|리조트/i, 'AD5'],
];

/**
 * 아는 업종이면 카카오 `category_group_code`, 모르면 null.
 * null 이면 지금까지처럼 이름 매칭에만 맡긴다 — 거르지 않는 쪽이 0건보다 낫다.
 */
export function kakaoCategoryFor(query: string): string | null {
  const q = query.replace(/\s+/g, '');
  if (!q) return null;
  for (const [re, code] of TABLE) if (re.test(q)) return code;
  return null;
}
