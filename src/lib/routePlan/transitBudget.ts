/**
 * 대중교통 `/transit` 호출 예산. 플래너(plan.ts)와 공급자(transitProvider.ts)가 같은 숫자를 본다 —
 * 두 곳이 따로 들고 있으면 한쪽만 고쳐져 예산이 조용히 새는 자리다(`server/src/guard.ts` 의 PER_DAY 와 같은 규칙).
 *
 * ## 왜 10인가
 *
 * Google Routes TRANSIT 은 경유지를 못 받는다. 그래서 대중교통은 route() 한 번을
 * **구간마다 한 번씩** `/transit` 으로 쪼개 부른다(자동차 `/route` 는 경유지를 그대로 실어 한 번).
 * 자동차는 계획 하나가 `/route` 를 최대 9회 쓴다 — 직행 1 + 시드 `SINGLE_R`=8.
 * 대중교통을 같은 자릿수 **10회**(직행 1 + 경유 조합 9)로 묶는다.
 *
 * 벽시계는 근거가 아니다 — 구간도 시드도 `Promise.all` 로 한 파도에 나가므로 호출을 늘려도
 * `runPlan` 의 12초에서 쓰는 건 구간 1회분(2026-09-16 실측 1.7~2.5초)이다. 묶는 이유는 돈이다.
 * 월 무료분 10,000 을 30 으로 나눈 일 300(`guard.ts`)이 계획 1건 = 10회로 바뀌었으므로,
 * 무료분 안에서 도는 대중교통 계획은 월 ~1,000 건이다.
 *
 * ## 시드 수는 고정 R 이 아니라 예산이 정한다
 *
 * 시드는 자동차와 같은 수로 **시도**하고(V=1 은 SINGLE_R=8, V≥2 는 DEFAULT_R=4),
 * 예산이 남아 있는 안만 실측한다. 비용은 **구간 단위로 중복을 뺀 뒤** 센다 — 시드들은
 * 한 번의 `Promise.all` 로 동시에 나가고 공급자가 같은 구간의 동시 요청을 하나로 합치므로,
 * 여러 시드에 겹치는 `O→c1` 같은 구간은 한 번만 나간다.
 *
 * 실사용은 V=1~2 다(실기기 `plan.start` 로그: V=2 아홉 번, V=1 한 번). 이 둘이 **완전 실측**으로
 * 예산 안에 들어오는 것이 이 숫자의 목표다.
 *
 *   V=1 · 구간 2개/안 · 시드끼리 겹치는 구간 **없음**(O→cᵢ, cᵢ→D 는 후보마다 전부 다르다)
 *        → 4안 × 2 = 8회 + 직행 1 = **9회**. 자동차의 8안에서 4안으로 잘린다.
 *   V=2 · 구간 3개/안 · 시드끼리 `O→c1`·`c1→b1`·`b1→D` 같은 구간을 공유한다
 *        → 겹침이 없으면 3안 × 3 = 9회(+직행 = 10회)
 *        → 겹치면 **4안이 8~9회**에 들어온다. 슬롯 2개 × 후보 2곳·순서 고정이면 안 4개의
 *          구간이 12개인데 서로 다른 구간은 8개다(3+2+2+1) → +직행 = **9회**.
 *          중복 제거가 없으면 12+1=13 이라 예산을 넘고 3안만 실측된다.
 *        → 어느 쪽이든 실측한 안은 **구간이 전부 실측**이라 `source: 'provider'` 다.
 *   V≥3 · 예산이 닿는 안만 실측하고 나머지는 추정으로 남는다(`scorePlan` 의 unknownLegs 가 센다).
 *        여기에 "어느 구간부터" 규칙은 두지 않는다 — 실사용에 없는 구간이고 마감이 9/21 이다.
 *
 * 아래 `transitSeedFloor` 는 **겹침이 하나도 없을 때 보장되는 하한**이다. 겹치면 그보다 많이 잰다.
 */

/** 계획 하나가 쓸 수 있는 `/transit` 총 호출 수. 직행 1회를 포함한다 */
export const TRANSIT_CALL_BUDGET = 10;

/** 직행이 쓰고 남는 몫 — 경유 조합 전부가 여기서 나눠 쓴다 */
export const TRANSIT_SEED_BUDGET = TRANSIT_CALL_BUDGET - 1;

/** 경유지 V곳인 안 하나의 구간 수 = 겹침이 없을 때의 호출 수 */
export const transitCallCost = (visits: number): number => visits + 1;

/** 겹침이 하나도 없을 때 보장되는 실측 안 수. V=1:4 · V=2:3 · V=3:2 */
export const transitSeedFloor = (visits: number): number =>
  Math.max(1, Math.floor(TRANSIT_SEED_BUDGET / transitCallCost(visits)));

/**
 * route() 한 번이 **실측할** 구간 수 상한. 넘는 구간은 추정으로 채우고 그 결과는 `'estimate'` 다 —
 * 잰 구간까지 버리지는 않는다. 경유 조합 몫 전부(9)라, 한 안이 예산을 다 먹는 건 허용하되 넘기지는 못한다.
 */
export const TRANSIT_MAX_LEGS_PER_ROUTE = TRANSIT_SEED_BUDGET;

/**
 * 계획 하나에서 **고른 매장을 다시 재는 데** 쓸 수 있는 호출 수. 위 10 과 별도로 얹힌다.
 *
 * ## 왜 4인가
 *
 * 교체 시트에서 후보 하나를 고르면 바뀌는 구간은 정확히 둘이다 — `prev→c`, `c→next`.
 * 그 둘만 물으면 '약'이 지워진다(`plan.ts` 의 `measureSwap`). 그러니 단위는 **고르기 1회 = 2회**고,
 * 4 는 **한 계획에서 두 번 고쳐 보는 것**까지 허용한다는 제품 문장이다. 세 번째부터는
 * 추정으로 남는다 — 못 고르는 게 아니라 '약'이 붙은 채 확정된다(`provider_direct_only` 와 같은 목소리).
 *
 * 왜 무제한이 아닌가: 시트를 위아래로 훑으며 고르면 한 계획이 `/transit` 을 수십 번 쓴다.
 * 계획 1건 상한이 10 → **14** 가 되면서, 일 300(`server/src/guard.ts` 의 `PER_DAY`)이 받는 계획은
 * 30건(안 고름) · 25건(1번) · 21건(2번)이다. 두 번까지는 실사용을 덮으면서 21건 밑으로는 안 내려간다.
 *
 * 대중교통 이름을 달고 있지만 **자동차·도보도 같은 천장을 쓴다**(`measureSwap`). 구간 하나는
 * 어느 모드에서나 2점짜리 호출 한 번이라 비용 셈이 같고, 모드마다 다른 숫자를 두면
 * 이 파일이 지키려는 "한 곳에서만 고친다"가 깨진다.
 */
export const TRANSIT_SWAP_BUDGET = 4;
